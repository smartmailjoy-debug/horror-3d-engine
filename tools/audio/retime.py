# Re-time the shot list to the generated VO, build vo_mix.wav, and write the old->new time map for the FX stem.
import json, re, numpy as np, wave
from scipy.signal import butter, sosfilt, fftconvolve
SR = 48000; D = "audio/"; RP = "engine/"
src = open(RP + "src/videos/t13/shots.ts").read()
items = [(n, float(t)) for n, t in re.findall(r'\{ n: "([0-9a-z]+)", t: ([0-9.]+),', src)]
items += [("120" + str(k), 559 + k * 1.2) for k in range(10)] + [("19" + c, 73 + k) for k, c in enumerate("abcde")]
items = [it for it in items if it[0] not in ("1", "2", "3", "4", "5", "6", "7", "8")]
items = sorted(items, key=lambda x: x[1]); items.append(("_", 620.0))
rows = json.load(open(D + "vo.json")); durs = {int(k): v for k, v in json.load(open(D + "vo/durs.json")).items()}
byshot = {}
for r in rows: byshot.setdefault("19a" if r["shot"] == "19" else r["shot"], []).append(r)
def readw(k):
    with wave.open(D + "vo/lines/%03d.wav" % k) as w: return np.frombuffer(w.readframes(w.getnframes()), "<i2").astype(np.float32) / 32767
LEAD = {"9": 0.6, "37": 0, "30": 0.4, "h1": 0.5, "h2": 0.4, "h7": 0.6}; TAIL = {"h1": 0.5, "h7": 1.2, "h5": 0.5, "30": 2.2, "36": 0.3, "8": 1.0, "57": 1.2, "94": 1.5, "111": 1.6, "121": 1.2, "122": 0.8, "129": 2.0}
order = [n for n, _ in items[:-1]]; oldt = dict(items); final = {}; place = []; cur = 0.0; i = 0
while i < len(order):
    n = order[i]; nxt = items[i + 1][1]; old = nxt - oldt[n]; ls = byshot.get(n, [])
    GR = {"19a": ["19a", "19b", "19c", "19d", "19e"], "h4a": ["h4a", "h4b", "h4c", "h4d"]}
    if n in GR:
        g = GR[n]; x = cur + 0.25
        for r in ls: place.append((x, r)); x += durs[r["k"]]
        span = max(len(g) * (1.0 if n == "19a" else 0.75), x - cur + 0.3) / len(g)
        for k, sn in enumerate(g): final[sn] = cur + span * k
        cur += span * len(g); i += len(g); continue
    final[n] = cur
    if not ls: cur += old; i += 1; continue
    x = cur + LEAD.get(n, 0.35)
    for j, r in enumerate(ls): place.append((x, r)); x += durs[r["k"]] + (0.5 if j < len(ls) - 1 else 0)
    cur += max(x - cur + TAIL.get(n, 0.55), min(old, 2.2)); i += 1
final["_"] = cur
total = final["_"]; print("new length", round(total, 1), "s  (was 620)")
json.dump({"new": final, "old": {n: t for n, t in items}}, open(D + "timemap.json", "w"), indent=0)
open(RP + "src/videos/t13/retime.ts", "w").write("// generated by t13audio/retime.py — shot starts re-timed to the ElevenLabs VO\nexport const RT: Record<string, number> = " + json.dumps({k: round(v, 3) for k, v in final.items()}) + ";\n")
# ---------- VO mix: narrator close + warm, radio EQ for *_r, Tower 13 voice ghosted
n = int((total + 2) * SR); L = np.zeros(n, np.float32); Rr = np.zeros(n, np.float32)
bp = lambda x, lo, hi: sosfilt(butter(4, [lo, hi], "band", fs=SR, output="sos"), x)
def comp(x, th=0.25, ratio=3.0):
    env = np.abs(x); env = np.convolve(env, np.ones(480) / 480, "same"); g = np.where(env > th, (th + (env - th) / ratio) / np.maximum(env, 1e-6), 1.0); return x * g
rng = np.random.default_rng(3)
for t, r in place:
    x = readw(r["k"]); spk = r["spk"]
    if spk.endswith("_r"):
        y = 0.75 * bp(x, 200, 5200) + 0.25 * x; y = np.tanh(y * 1.25) / np.tanh(1.25)  # light radio colour, speech stays clear
        if spk == "t13_r" or (spk == "arjun_r" and r["shot"] in ("127", "128", "129")) or (spk == "rinku_r" and r["shot"] == "56"):
            d = int(0.018 * SR); y = y + np.concatenate([np.zeros(d), y[:-d]]) * 0.35  # faint doubling only, no echo tail
        y = comp(y.astype(np.float32), 0.25, 2.2); pan = 0.0
    else:
        y = comp(x, 0.25, 2.4) * 1.0; pan = 0.0
    i0 = int(t * SR); i1 = min(n, i0 + len(y)); L[i0:i1] += y[: i1 - i0] * (1 - pan * 0.5); Rr[i0:i1] += y[: i1 - i0] * (1 + pan * 0.5)
mix = np.stack([L, Rr], 1); mix *= 0.9 / max(1e-6, np.abs(mix).max())
with wave.open(RP + "public/t13/vo_mix.wav", "wb") as w: w.setnchannels(2); w.setsampwidth(2); w.setframerate(SR); w.writeframes((mix * 32767).astype("<i2").tobytes())
json.dump([(round(t, 2), r["shot"], r["spk"], r["k"]) for t, r in place], open(D + "vo_place.json", "w"))
SPK = {"bhola": "bhola", "bhola_r": "bhola", "rinku_r": "rinku", "sameer": "sameer", "sameer_r": "sameer", "mohan_r": "mohan", "dev_r": "dev", "kishan_r": "kishan", "barua": "barua", "arjun_r": "arjun"}
talk = {}
for t, r in place:
    who = SPK.get(r["spk"]);
    if not who: continue
    x = readw(r["k"]); hop = int(SR / 30); e = np.array([np.sqrt(np.mean(x[i:i + hop] ** 2)) for i in range(0, len(x) - hop, hop)]); thr = max(0.02, e.max() * 0.22)
    on = e > thr; # alternate open/closed on syllables: open when energy above threshold and rising/peaking
    k = 0
    while k < len(on):
        if on[k]:
            j = k
            while j < len(on) and on[j] and j - k < 4: j += 1
            talk.setdefault(who, []).append([round(t + k / 30, 3), round(t + j / 30, 3)]); k = j + 1
        else: k += 1
for v in talk.values(): v.sort()
open(RP + "src/videos/t13/talk.ts", "w").write("// generated by t13audio/retime.py — mouth-open windows (film seconds) per character, from the VO energy\nexport const TALK: Record<string, [number, number][]> = " + json.dumps(talk) + ";\n")
print("placed", len(place))
